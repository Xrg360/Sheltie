"""DNS side: names and validation, CoreDNS config files, and a tiny resolver for self-checks."""

from __future__ import annotations

import os
import random
import re
import socket
import struct
import tempfile

LABEL = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")
RESERVED = {"dns"}  # dns.<zone> is the address of the DNS server itself


def label_error(value: str, what: str = "Name") -> str | None:
    """Explain why value isn't a valid single DNS label, or None if it is."""
    if not value:
        return f"{what} can't be empty."
    if len(value) > 63:
        return f"{what} must be 63 characters or fewer."
    if not LABEL.match(value):
        return f"{what} can use only a-z, 0-9 and hyphens, and can't start or end with a hyphen."
    return None


def zone_error(label: str, tld: str) -> str | None:
    for part in label.split("."):
        err = label_error(part, "Each part of the domain")
        if err:
            return err
    err = label_error(tld, "The TLD")
    if err:
        return err
    if tld.isdigit():
        return "The TLD can't be only digits."
    if len(label) + len(tld) + 1 > 200:
        return "That domain is too long."
    return None


# --- CoreDNS files ------------------------------------------------------------

def _write_atomic(path: str, text: str) -> None:
    folder = os.path.dirname(path)
    os.makedirs(folder, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=folder, prefix=".tmp-")
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def render_zone(zone: str, records: list[tuple[str, str]], serial: int, ns_ip: str) -> str:
    lines = [
        "; Generated by Sheltie. Edits here are overwritten.",
        f"$ORIGIN {zone}.",
        f"@ 60 IN SOA dns.{zone}. hostmaster.{zone}. {serial} 3600 600 86400 60",
        f"@ 60 IN NS dns.{zone}.",
    ]
    seen = set()
    for name, ip in [("dns", ns_ip)] + records:
        if name in seen or not ip:
            continue
        seen.add(name)
        rtype = "AAAA" if ":" in ip else "A"
        lines.append(f"{name} 60 IN {rtype} {ip}")
    return "\n".join(lines) + "\n"


def render_corefile(zone: str, bind_ip: str, zone_path: str) -> str:
    return (
        "# Generated by Sheltie. Edits here are overwritten.\n"
        f"{zone}:53 {{\n"
        f"    bind {bind_ip}\n"
        f"    file {zone_path} {{\n"
        "        reload 2s\n"
        "    }\n"
        "    reload 2s\n"
        "    errors\n"
        "}\n"
    )


def write_coredns(dns_dir: str, coredns_dir: str, zone: str, bind_ip: str,
                  records: list[tuple[str, str]], serial: int, ns_ip: str) -> None:
    """Write the zone file first, then point the Corefile at it.

    Each zone gets its own file, so renaming the domain swaps files atomically
    instead of editing a file CoreDNS is reading.
    """
    zone_file = f"{zone}.db"
    _write_atomic(os.path.join(dns_dir, zone_file), render_zone(zone, records, serial, ns_ip))
    _write_atomic(os.path.join(dns_dir, "Corefile"),
                  render_corefile(zone, bind_ip, f"{coredns_dir}/{zone_file}"))
    for name in os.listdir(dns_dir):
        if name.endswith(".db") and name != zone_file:
            try:
                os.remove(os.path.join(dns_dir, name))
            except OSError:
                pass


# --- resolver for self-checks ---------------------------------------------------

def _skip_name(msg: bytes, pos: int) -> int:
    while True:
        length = msg[pos]
        if length == 0:
            return pos + 1
        if length & 0xC0 == 0xC0:
            return pos + 2
        pos += 1 + length


def query_a(server: str, name: str, port: int = 53, timeout: float = 2.0) -> tuple[int, list[str]]:
    """Ask `server` for the A records of `name`. Returns (rcode, addresses)."""
    tid = random.randint(0, 0xFFFF)
    qname = b"".join(bytes([len(p)]) + p.encode() for p in name.rstrip(".").split(".")) + b"\0"
    packet = struct.pack(">HHHHHH", tid, 0x0100, 1, 0, 0, 0) + qname + struct.pack(">HH", 1, 1)
    family = socket.AF_INET6 if ":" in server else socket.AF_INET
    with socket.socket(family, socket.SOCK_DGRAM) as sock:
        sock.settimeout(timeout)
        sock.sendto(packet, (server, port))
        while True:
            msg, _ = sock.recvfrom(4096)
            if len(msg) >= 12 and struct.unpack(">H", msg[:2])[0] == tid:
                break
    flags, qd, an = struct.unpack(">HHH", msg[2:8])
    pos = 12
    for _ in range(qd):
        pos = _skip_name(msg, pos) + 4
    addrs = []
    for _ in range(an):
        pos = _skip_name(msg, pos)
        rtype, _cls, _ttl, rdlen = struct.unpack(">HHIH", msg[pos : pos + 10])
        pos += 10
        if rtype == 1 and rdlen == 4:
            addrs.append(socket.inet_ntoa(msg[pos : pos + 4]))
        pos += rdlen
    return flags & 0xF, addrs
